export function classById(id: string): MosqueClass | undefined {
  return classes.find((mosqueClass) => mosqueClass.id === id);
}

/** Classes taking students right now — the ones an enrolment figure should count. */
const activeClasses = classes.filter(
  (mosqueClass) =>
    mosqueClass.status === "Enrolling" || mosqueClass.status === "Ongoing" || mosqueClass.status === "Full",
);

export const classStats = {
  total: classes.length,
  enrolling: classes.filter((mosqueClass) => mosqueClass.status === "Enrolling").length,
  studentsEnrolled: activeClasses.reduce((sum, mosqueClass) => sum + mosqueClass.enrolled, 0),
  openPlaces: classes
    .filter((mosqueClass) => mosqueClass.status === "Enrolling")
    .reduce((sum, mosqueClass) => sum + Math.max(0, mosqueClass.capacity - mosqueClass.enrolled), 0),
};
