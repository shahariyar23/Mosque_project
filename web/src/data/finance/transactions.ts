/**
 * The six newest entries, shown on the overview. Sorted here rather than relying on the literal's
 * order: the rows above are written newest-id-first for readability, but ids and dates do not run
 * in lockstep, so slicing raw would put 21 August above two 22 August entries.
 */
export const recentTransactions = [...transactions]
  .sort((a, b) => (a.date === b.date ? b.id.localeCompare(a.id) : b.date.localeCompare(a.date)))
  .slice(0, 6);

export function getTransaction(id: string): Transaction | undefined {
  return transactions.find((transaction) => transaction.id === id);
}
