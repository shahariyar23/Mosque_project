export function khutbahEntryById(id: string): KhutbahEntry | undefined {
  return khutbahEntries.find((entry) => entry.id === id);
}

const delivered = khutbahEntries.filter((entry) => entry.status === "Delivered");
const attendanceTotal = delivered.reduce((sum, entry) => sum + (entry.attendance ?? 0), 0);

export const khutbahStats = {
  total: khutbahEntries.length,
  delivered: delivered.length,
  scheduled: khutbahEntries.filter((entry) => entry.status === "Scheduled").length,
  avgAttendance: delivered.length > 0 ? Math.round(attendanceTotal / delivered.length) : 0,
};
