/** Recent bookings for one service, newest request first — used by the service detail drawer. */
export function bookingsForService(serviceId: string): Booking[] {
  return bookings
    .filter((booking) => booking.serviceId === serviceId)
    .sort((a, b) => b.submittedAt.localeCompare(a.submittedAt));
}

/**
 * Headline figures for the bookings summary strip. "This week" counts confirmed or pending requests
 * scheduled in the seven days from the reference date, which is the queue the office actually works.
 */
const WEEK_START = "2026-08-23";
const WEEK_END = "2026-08-30";

